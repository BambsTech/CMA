// Builds production image assets from /assets-src.
// - High-quality WebP masters of the three AI concept images (desktop + mobile).
// - Art-directed detail crops, so the site does not repeat the same three frames.
// - Brand logo SVG files in approved colourways (paths extracted 1:1 from the official manual).
// - Favicon / app icons from the official reduced logotype (CM&A).
// Usage: npm run assets
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = (...p) => path.join(root, "assets-src", ...p);
const out = (...p) => path.join(root, "public", "assets", ...p);

const A = src("architecture", "HERO_A_Cinematic_Colonnade_AI.png");
const B = src("architecture", "HERO_B_Golden_Pavilion_AI.png");
const C = src("architecture", "HERO_C_Shadow_Corridor_AI.png");

// [file, source, crop{left,top,width,height} | null, max width]
const images = [
  ["colonnade.webp", A, null, 1672],
  ["pavilion.webp", B, null, 1672],
  ["corridor.webp", C, null, 1672],
  ["detail-colonnade-rhythm.webp", A, { left: 940, top: 0, width: 732, height: 941 }, 732],
  ["detail-curved-wall.webp", A, { left: 0, top: 60, width: 560, height: 840 }, 560],
  ["detail-glass-reflection.webp", B, { left: 0, top: 40, width: 600, height: 900 }, 600],
  ["detail-horizon.webp", B, { left: 760, top: 120, width: 912, height: 600 }, 912],
  ["detail-leaf-shadow.webp", C, { left: 0, top: 80, width: 560, height: 840 }, 560],
  ["detail-floor-light.webp", C, { left: 120, top: 560, width: 1500, height: 381 }, 1500],
  ["detail-vanishing-point.webp", C, { left: 420, top: 60, width: 640, height: 880 }, 640],
  ["detail-ceiling.webp", A, { left: 380, top: 0, width: 760, height: 520 }, 760],
];

const mobile = [
  ["colonnade-mobile.webp", src("architecture", "HERO_A_Cinematic_Colonnade_AI_MOBILE_CROP.webp")],
  ["pavilion-mobile.webp", src("architecture", "HERO_B_Golden_Pavilion_AI_MOBILE_CROP.webp")],
  ["corridor-mobile.webp", src("architecture", "HERO_C_Shadow_Corridor_AI_MOBILE_CROP.webp")],
];

// Approved colourways — taken from the manual's own variant grids (pp. 12, 14, 16, 18, 20).
const colourways = {
  espresso: "#301206",
  stone: "#CECBC4",
  taupe: "#ACA699",
  slate: "#B4B9BF",
  earth: "#382C23",
  white: "#FFFFFF",
  black: "#000000",
};
const logos = [
  "cma-monograma",
  "cma-logotipo-completo-horizontal",
  "cma-logotipo-completo-vertical",
  "cma-logotipo-nome-horizontal",
  "cma-logotipo-nome-vertical",
];

async function main() {
  await fs.mkdir(out("architecture"), { recursive: true });
  await fs.mkdir(out("brand"), { recursive: true });
  await fs.mkdir(out("icons"), { recursive: true });

  for (const [name, file, crop, w] of images) {
    let img = sharp(file);
    if (crop) img = img.extract(crop);
    await img.resize({ width: w, withoutEnlargement: true }).webp({ quality: 86, effort: 6 }).toFile(out("architecture", name));
    console.log("architecture/" + name);
  }
  for (const [name, file] of mobile) {
    await sharp(file).webp({ quality: 84, effort: 6 }).toFile(out("architecture", name));
    console.log("architecture/" + name);
  }

  // Logo files: one neutral (currentColor) master + approved colourways.
  for (const logo of logos) {
    const svg = await fs.readFile(src("brand-extracted", logo + ".svg"), "utf8");
    await fs.writeFile(out("brand", logo + ".svg"), svg);
    for (const [cw, hex] of Object.entries(colourways)) {
      if (cw === "earth" || cw === "slate" || cw === "taupe") continue; // used only as backgrounds
      await fs.writeFile(out("brand", `${logo}-${cw}.svg`), svg.replace('fill="currentColor"', `fill="${hex}"`));
    }
  }

  // Typed logo module for the <Logo/> component (inline SVG, inherits currentColor).
  const entries = [];
  for (const logo of logos) {
    const svg = await fs.readFile(src("brand-extracted", logo + ".svg"), "utf8");
    const [, w, h] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
    const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    const key = logo.replace("cma-", "").replace("logotipo-", "");
    entries.push(`  "${key}": { width: ${w}, height: ${h}, markup: ${JSON.stringify(inner)} },`);
  }
  await fs.mkdir(path.join(root, "src", "components", "brand"), { recursive: true });
  await fs.writeFile(
    path.join(root, "src", "components", "brand", "logo-data.ts"),
    `// GENERATED by scripts/build-images.mjs — do not edit by hand.\n// Vector paths extracted 1:1 from the official CMA brand manual (Estúdio Sarau, 2025), pp. 12–20.\nexport const LOGOS = {\n${entries.join("\n")}\n} as const;\nexport type LogoVariant = keyof typeof LOGOS;\n`,
  );

  // Icon: official reduced logotype, stone on espresso (approved pairing), centred with clear space.
  const mono = await fs.readFile(src("brand-extracted", "cma-monograma.svg"), "utf8");
  const vb = mono.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  const [mw, mh] = [parseFloat(vb[1]), parseFloat(vb[2])];
  const inner = mono.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  const iconSvg = (size, pad) => {
    const scale = (size - pad * 2) / mw;
    const ty = (size - mh * scale) / 2;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${colourways.espresso}"/><g fill="${colourways.stone}" transform="translate(${pad} ${ty.toFixed(3)}) scale(${scale.toFixed(5)})">${inner}</g></svg>`;
  };
  await fs.writeFile(out("icons", "icon.svg"), iconSvg(512, 64));
  await fs.writeFile(path.join(root, "src", "app", "icon.svg"), iconSvg(512, 64));
  for (const [file, size, pad] of [
    ["icon-32.png", 32, 2],
    ["apple-touch-icon.png", 180, 22],
    ["icon-192.png", 192, 24],
    ["icon-512.png", 512, 64],
  ]) {
    await sharp(Buffer.from(iconSvg(size * 4, pad * 4))).resize(size, size).png().toFile(out("icons", file));
  }
  await fs.copyFile(out("icons", "apple-touch-icon.png"), path.join(root, "src", "app", "apple-icon.png"));
  console.log("icons done");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
