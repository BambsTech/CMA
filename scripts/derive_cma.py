"""Derive the CMA institutional wordmark from the official vector outlines.

Nothing is redrawn: the C, M and A of the manual's reduced logo (monograma) and the
ADVOGADOS letters of the official signature are re-spaced only — the "&" and its rule are
left out. The result is a proposal (client approval pending, see CLIENT_APPROVAL_REQUIRED.md).

Run: python3 scripts/derive_cma.py  →  src/components/brand/cma-data.ts
"""
import re, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "src/components/brand/logo-data.ts").read_text()


def paths_of(key):
    i = src.find(f'"{key}"')
    line = src[i : src.find("\n", i)]
    w, h = map(float, re.search(r"width: ([\d.]+), height: ([\d.]+)", line).groups())
    mk = re.search(r'markup: "(.*)" \}', line).group(1).encode().decode("unicode_escape")
    out = []
    for d in re.findall(r'<path d="([^"]*)"', mk):
        nums = [float(x) for x in re.findall(r"-?\d+\.?\d*", d)]
        out.append((d, min(nums[0::2]), max(nums[0::2])))
    return out, w, h


def group(d_list, dx):
    body = "".join(f'<path d="{d}"/>' for d in d_list)
    return f'<g transform="translate({dx:.3f} 0)">{body}</g>' if abs(dx) > 1e-6 else body


# — CMA: C (x≈0–25.8), M (29.4–66.6), & (77.8–92.7, dropped), A (95.3–123.7)
mono, _, mh = paths_of("monograma")
C = [d for d, a, b in mono if b < 27]
M = [d for d, a, b in mono if 28 < a < 30]
A = [d for d, a, b in mono if a > 94]
GAP = 4.2  # M→A, close to the C→M spacing of the original artwork (3.6)
shift = (66.6 + GAP) - 95.3
cma_w = 123.684 + shift
cma = "".join(f'<path d="{d}"/>' for d in C + M) + group(A, shift)

# — ADVOGADOS: the signature's "& ADVOGADOS" without the ampersand
adv, aw, ah = paths_of("palavra-advogados")
letters = [d for d, a, b in adv if a > 10]
adv_markup = group(letters, -19.166)
adv_w = aw - 19.166

out = f"""/* Generated by scripts/derive_cma.py — do not edit by hand.
 * Re-spaced official outlines (no redrawing). Proposal pending client approval. */
export const CMA_MARKS = {{
  cma: {{ width: {cma_w:.3f}, height: {mh}, markup: {json.dumps(cma)} }},
  advogados: {{ width: {adv_w:.3f}, height: {ah}, markup: {json.dumps(adv_markup)} }},
}} as const;
"""
(ROOT / "src/components/brand/cma-data.ts").write_text(out)
print("cma", round(cma_w, 2), "x", mh, "| advogados", round(adv_w, 2), "x", ah)
